static void trace_test_emit(unsigned frame)
{
    const unsigned half=frame&1U;
    for(unsigned key=0;key<7U;key++)
        scan_buffer.samples[half*7U+key]=trace_test_raw(frame,key);
    clock_us=frame*1000000U/SCAN_TARGET_HZ;
    const uint32_t remaining=half?14U:7U;
    interrupt(half?DMA_LISR_TCIF0:DMA_LISR_HTIF0,remaining,remaining,
              (frame+1U)*(240000000U/SCAN_TARGET_HZ));
}
static void test_trace_reseed_is_rejected(void)
{
    reset();
    for(unsigned frame=0;frame<10U;frame++)trace_test_emit(frame);
    c77_sample_t sample={0};adc_trace_history history;
    const uint8_t keys[ADC_TRACE_KEYS]={5U,6U};
    assert(adc_scan_trace_snapshot(&sample,&history,keys));
    scan_buffer.samples[5]=5000U;
    interrupt(DMA_LISR_HTIF0,7U,7U,11U*(240000000U/SCAN_TARGET_HZ));
    assert(scan_state.errors==1U && !local_hall_filter.ready);
    assert(!adc_scan_trace_snapshot(&sample,&history,keys));
    trace_test_emit(11U);
    assert(scan_state.sample_seq==12U && local_hall_filter.ready);
    assert(adc_scan_snapshot(&sample) && sample.hall_filtered_valid);
    /* A re-seed creates copies, not eight actual consecutive samples. */
    assert(!adc_scan_trace_snapshot(&sample,&history,keys));
}
