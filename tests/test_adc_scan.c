bool adc_scan_snapshot(c77_sample_t *out);
#else
static volatile c77_sample_t input_frame;
#endif
static uint32_t previous_publish_cycle,have_previous_publish,expected_half;
#if HARDWARE_REVISION==86 && ROLE_LEFT
#define LOCAL_HALL_FILTER_SAMPLES (SCAN_TARGET_HZ==16000U ? 2U : 8U)
static hall_filter_t local_hall_filter;
#endif
static uint32_t clock_us,input_calls,input_errors;
uint32_t board_micros(void) { return clock_us; }
static void board_input_scan(c77_sample_t *sample)
{
#if HARDWARE_REVISION==86 && ROLE_LEFT
    if(inspect_during_write) assert(adc_scan_snapshot(&frame_during_write));
#endif
    sample->digital=5U;sample->encoders[0]=12U;sample->encoders[1]=23U;
    sample->errors+=input_errors;
    ++input_calls;
    DWT->CYCCNT+=37U; /* Test the diagnostic counter, not physical execution. */
}
void HAL_ADC_ErrorCallback(ADC_HandleTypeDef *adc);
static uint32_t HAL_ADC_GetError(ADC_HandleTypeDef *adc) { return adc->ErrorCode; }
static void HAL_ADC_IRQHandler(ADC_HandleTypeDef *adc)
{
    if(adc->Instance->ISR&ADC_FLAG_OVR) {
        adc->ErrorCode|=HAL_ADC_ERROR_OVR;
        HAL_ADC_ErrorCallback(adc);
    }
}

