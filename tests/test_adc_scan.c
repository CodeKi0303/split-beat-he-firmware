static void reset(void)
{
    memset((void*)&scan_state,0,sizeof scan_state);
#if HARDWARE_REVISION==86 && ROLE_LEFT
    memset(input_frames,0,sizeof input_frames);
    published_frame=0U;
    inspect_during_write=false;
    hall_filter_reset(&local_hall_filter);
#else
    memset((void*)&input_frame,0,sizeof input_frame);
#endif
    scan_state.running=1U;scan_state.period_min_cycles=UINT32_MAX;
    scan_adc.Instance=&adc_registers;scan_adc.ErrorCode=0;scan_adc.State=0;
    scan_dma.ErrorCode=0;adc_registers.ISR=0;
    timer_registers.CR1=TIM_CR1_CEN;dma_registers.LISR=0;dma_registers.LIFCR=0;
    cycle_registers.CYCCNT=0;clock_us=0;input_calls=0;input_errors=0;dma_disabled=0;
    expected_half=0;have_previous_publish=0;previous_publish_cycle=0;
    counter_before=SPLIT_ADC_RANKS;counter_after=SPLIT_ADC_RANKS;counter_reads=0;
    enabled_adc_irqs=ADC_IT_OVR;
    enabled_dma_irqs=DMA_IT_TC|DMA_IT_HT|DMA_IT_TE|DMA_IT_DME;
    basepri=highest_mask=0;
    for(unsigned i=0;i<2U*SPLIT_ADC_RANKS;++i)scan_buffer.samples[i]=(uint16_t)(100U+i);
}
static void interrupt(uint32_t flags,uint32_t before,uint32_t after,uint32_t cycle)
{
    dma_registers.LISR=flags;counter_before=before;counter_after=after;counter_reads=0;
    DWT->CYCCNT=cycle;
    DMA2_Stream0_IRQHandler();
}
static void stopped_without_publish(void)
{
    assert(scan_state.running==0U && scan_state.sample_seq==0U && input_calls==0U);
    assert((TIM3->CR1&TIM_CR1_CEN)==0U);
    assert(enabled_adc_irqs==0U && enabled_dma_irqs==0U);
    c77_sample_t sample={0};assert(!adc_scan_snapshot(&sample));
}
static void test_complete_sequences(void)
{
    reset();
    const uint32_t cycles_per_scan=240000000U/SCAN_TARGET_HZ;
    for(uint32_t i=0;i<128U;++i) {
        uint32_t half=i&1U;
        uint32_t remaining=half?2U*SPLIT_ADC_RANKS:SPLIT_ADC_RANKS;
        clock_us=(i*1000000U)/SCAN_TARGET_HZ;
        interrupt(half?DMA_LISR_TCIF0:DMA_LISR_HTIF0,remaining,remaining,(i+1U)*cycles_per_scan);
        c77_sample_t sample={0};assert(adc_scan_snapshot(&sample));
        assert(sample.sequence==i+1U && sample.digital==5U && sample.encoders[1]==23U);
        for(unsigned rank=0;rank<SPLIT_ADC_RANKS;++rank)
            assert(sample.raw[rank]==100U+half*SPLIT_ADC_RANKS+rank);
#if HARDWARE_REVISION==86 && ROLE_LEFT
        assert(sample.hall_filtered_valid==1U);
        if(i==0U) assert(sample.hall_filtered[0]==100U);
        if(i>=LOCAL_HALL_FILTER_SAMPLES) assert(sample.hall_filtered[0]==104U);
#else
        assert(sample.hall_filtered_valid==0U && sample.hall_filtered[0]==0U);
#endif
        assert(sample.timestamp_us==clock_us && sample.errors==0U);
#if HARDWARE_REVISION==86 && ROLE_LEFT
        assert(published_frame==((i+1U)&1U));
#endif
    }
    assert(scan_state.period_min_cycles==cycles_per_scan);
    assert(scan_state.period_max_cycles==cycles_per_scan);
    assert(scan_state.irq_max_cycles==37U && scan_state.errors==0U);
    assert(input_calls==128U && expected_half==0U);
    assert(DMA2->LIFCR==DMA_LIFCR_CTCIF0);
    assert(highest_mask==(SCAN_ADC_IRQ_PRIORITY<<(8U-__NVIC_PRIO_BITS)) && basepri==0U);
    /* Clock/interrupt counters wrap safely at 32 bits. */
    reset();
    interrupt(DMA_LISR_HTIF0,7U,7U,UINT32_MAX-1000U);
    interrupt(DMA_LISR_TCIF0,14U,14U,UINT32_MAX-1000U+cycles_per_scan);
    assert(scan_state.period_min_cycles==cycles_per_scan);
    assert(scan_state.period_max_cycles==cycles_per_scan);
}
