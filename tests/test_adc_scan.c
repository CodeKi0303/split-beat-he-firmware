static void test_publication_is_coherent(void)
{
    reset();
    input_errors=2U;
    interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    inspect_during_write=true;
    clock_us=16U;
    interrupt(DMA_LISR_TCIF0,14U,14U,3850U);
    assert(frame_during_write.sequence==1U && frame_during_write.raw[0]==100U);
    assert(frame_during_write.timestamp_us==0U && frame_during_write.encoders[1]==23U);
    c77_sample_t after={0};
    assert(adc_scan_snapshot(&after));
    assert(after.sequence==2U && after.raw[0]==107U && after.timestamp_us==16U);

    inspect_during_write=false;
    scan_buffer.samples[0]=5000U;
    interrupt(DMA_LISR_HTIF0,7U,7U,7600U);
    assert(adc_scan_snapshot(&after));
    assert(after.sequence==3U && after.raw[0]==5000U && after.errors==2U+2U*SCAN_ADC_CAPTURE_DIAG);
    assert(!after.hall_filtered_valid && after.hall_filtered[0]==0U);

    /* The fourth scan can write its slot before DMA ownership is lost. */
    interrupt(DMA_LISR_TCIF0,14U,7U,11400U);
    assert(!adc_scan_snapshot(&after));
    assert(scan_state.late_irqs==1U && after.sequence==3U && after.raw[0]==5000U);
}
