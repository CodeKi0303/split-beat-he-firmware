static void test_dma_ownership(void)
{
    reset();interrupt(DMA_LISR_HTIF0|DMA_LISR_TCIF0,7U,7U,100U);
    stopped_without_publish();assert(scan_state.late_irqs==1U);
    reset();interrupt(DMA_LISR_TCIF0,14U,14U,100U); /* Unexpected first half. */
    stopped_without_publish();assert(scan_state.late_irqs==1U);
    reset();interrupt(DMA_LISR_HTIF0,14U,7U,100U); /* DMA still owns buffer. */
    stopped_without_publish();assert(scan_state.late_irqs==1U);
    reset();interrupt(DMA_LISR_HTIF0,7U,14U,100U); /* DMA wrapped during copy. */
    stopped_without_publish();assert(scan_state.late_irqs==1U);
    reset();interrupt(DMA_LISR_HTIF0,0U,0U,100U); /* Half zero is not safe at reload. */
    stopped_without_publish();
    reset();interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    interrupt(DMA_LISR_TCIF0,0U,0U,200U); /* Half one is safe just at reload. */
    assert(scan_state.sample_seq==2U && scan_state.errors==0U);
    reset();interrupt(DMA_LISR_FEIF0|DMA_LISR_HTIF0,7U,7U,100U);
    assert(scan_state.sample_seq==1U); /* Ignore disabled FIFO status. */
}
static void test_errors_and_staleness(void)
{
    reset();interrupt(DMA_LISR_TEIF0|DMA_LISR_HTIF0,7U,7U,100U);
    stopped_without_publish();assert(scan_state.dma_errors==1U && dma_disabled==1U);
    assert((scan_dma.ErrorCode&HAL_DMA_ERROR_TE)!=0U);
    reset();enabled_dma_irqs|=DMA_IT_FE;
    interrupt(DMA_LISR_DMEIF0|DMA_LISR_FEIF0,7U,7U,100U);
    stopped_without_publish();assert(scan_dma.ErrorCode==(HAL_DMA_ERROR_DME|HAL_DMA_ERROR_FE));
    reset();adc_registers.ISR=ADC_FLAG_OVR;interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    stopped_without_publish();assert(scan_state.overruns==1U);
    reset();interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    clock_us=1000U;c77_sample_t sample={0};assert(adc_scan_snapshot(&sample));
    clock_us=1001U;assert(!adc_scan_snapshot(&sample));
    clock_us=0U;scan_state.running=0U;assert(!adc_scan_snapshot(&sample));
    assert(!adc_scan_snapshot(NULL));
    split_adc_snapshot stats={0};basepri=0x30U;adc_scan_stats(&stats);
    assert(stats.sample_seq==1U && stats.raw[6]==106U && stats.irq_max_cycles==37U);
    assert(basepri==0x30U);adc_scan_stats(NULL);
    /* A previously published sample is never revalidated after a late IRQ. */
    reset();interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    interrupt(DMA_LISR_HTIF0|DMA_LISR_TCIF0,7U,7U,200U);
    assert(!adc_scan_snapshot(&sample) && sample.sequence==1U && sample.errors==1U);
}
static void test_filter_publication(void)
{
#if HARDWARE_REVISION==86 && ROLE_LEFT
    reset();
    for(unsigned i=0;i<2U*SPLIT_ADC_RANKS;i++) scan_buffer.samples[i]=2200U;
    interrupt(DMA_LISR_HTIF0,7U,7U,100U);
    c77_sample_t sample={0};assert(adc_scan_snapshot(&sample));
    assert(sample.hall_filtered_valid && sample.hall_filtered[0]==2200U);
    /* A raw impulse remains observable, but decision data is attenuated.
     * Updating exactly at publication makes this independent of main-loop skips. */
    scan_buffer.samples[SPLIT_ADC_RANKS]=2280U;
    interrupt(DMA_LISR_TCIF0,14U,14U,200U);
    assert(adc_scan_snapshot(&sample));
    assert(sample.raw[0]==2280U && scan_state.raw[0]==2280U);
    assert(sample.hall_filtered[0]==2200U+80U/LOCAL_HALL_FILTER_SAMPLES);
    assert(sample.hall_filtered[1]==2200U);
    hall_filter_t before=local_hall_filter;
    interrupt(DMA_LISR_HTIF0,7U,14U,300U); /* Ownership changed during copy. */
    assert(!adc_scan_snapshot(&sample));
    assert(before.ready && !local_hall_filter.ready); /* Error discards history. */
    /* Re-starting at a different constant does not reuse the old history. */
    reset();
    for(unsigned i=0;i<2U*SPLIT_ADC_RANKS;i++) scan_buffer.samples[i]=3000U;
    interrupt(DMA_LISR_HTIF0,7U,7U,400U);
    assert(adc_scan_snapshot(&sample) && sample.hall_filtered[0]==3000U);
    scan_buffer.samples[SPLIT_ADC_RANKS]=5000U;
    interrupt(DMA_LISR_TCIF0,14U,14U,500U);
    assert(adc_scan_snapshot(&sample) && sample.raw[0]==5000U);
    assert(!sample.hall_filtered_valid && !local_hall_filter.ready);
    /* The invalid raw is deliberately not turned into a plausible average;
     * the downstream engine rejects it, and the next good scan reseeds. */
    interrupt(DMA_LISR_HTIF0,7U,7U,600U);
    assert(adc_scan_snapshot(&sample) && sample.hall_filtered[0]==3000U);
#endif
}
